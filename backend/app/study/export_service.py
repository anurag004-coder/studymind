"""Export Service for Anki CSV and Markdown/PDF Study Guide per PRD §4."""

import csv
import io
import json

from app.db.models import StudyItem


class ExportService:
    """Exports study items to Anki-compatible CSV/TSV and formatted Study Guides."""

    @staticmethod
    def export_anki_tsv(items: list[StudyItem]) -> str:
        """Exports flashcards and quiz questions to Anki TSV format (Front \\t Back \\t Tags)."""
        output = io.StringIO()
        # Anki standard separator is Tab (\t)
        writer = csv.writer(output, delimiter="\t", quoting=csv.QUOTE_MINIMAL)

        for item in items:
            try:
                data = json.loads(item.payload_json)
            except Exception:
                continue

            if item.type == "flashcard":
                q = data.get("question", "").strip()
                ans = data.get("answer", "").strip()
                quote = data.get("quote", "").strip()
                page = data.get("page")

                page_info = f" (Page {page})" if page else ""
                source_meta = f"&ldquo;{quote}&rdquo;{page_info}"
                back_html = (
                    f"{ans}<br><br><small style='color:#666;'><b>Source:</b> {source_meta}</small>"
                )
                writer.writerow([q, back_html, "studymind studymind-flashcard"])

            elif item.type == "quiz":
                stem = data.get("stem", "").strip()
                options = data.get("options", [])
                corr_idx = data.get("correct_answer_index", 0)
                explanation = data.get("explanation", "").strip()
                quote = data.get("quote", "").strip()

                letters = ["A", "B", "C", "D"]
                opt_html = "<br>".join(
                    f"<b>{letters[i] if i < len(letters) else i + 1}.</b> {opt}"
                    for i, opt in enumerate(options)
                )
                front_html = f"{stem}<br><br>{opt_html}"

                corr_letter = letters[corr_idx] if corr_idx < len(letters) else "A"
                corr_text = options[corr_idx] if corr_idx < len(options) else ""
                proof_html = (
                    f"<small style='color:#666;'><b>Proof:</b> &ldquo;{quote}&rdquo;</small>"
                )
                back_html = (
                    f"<b>Correct Answer:</b> {corr_letter}. {corr_text}<br><br>"
                    f"<b>Explanation:</b> {explanation}<br><br>"
                    f"{proof_html}"
                )
                writer.writerow([front_html, back_html, "studymind studymind-quiz"])

        return output.getvalue()

    @staticmethod
    def export_study_guide_markdown(
        items: list[StudyItem], workspace_name: str = "StudyMind Workspace"
    ) -> str:
        """Exports all study items into a comprehensive Markdown Study Guide."""
        lines = [
            f"# Study Guide: {workspace_name}",
            "*Generated by StudyMind — Verified Grounded Materials*\n",
            "---",
        ]

        summaries = [it for it in items if it.type == "summary"]
        flashcards = [it for it in items if it.type == "flashcard"]
        quizzes = [it for it in items if it.type == "quiz"]

        if summaries:
            lines.append("## 1. Course Summaries & Key Takeaways\n")
            for idx, s in enumerate(summaries, 1):
                try:
                    data = json.loads(s.payload_json)
                    title = data.get("title", f"Summary {idx}")
                    summary_text = data.get("summary", "")
                    takeaways = data.get("key_takeaways", [])

                    lines.append(f"### {title}\n")
                    lines.append(f"{summary_text}\n")
                    if takeaways:
                        lines.append("#### Key Takeaways")
                        for t in takeaways:
                            page_info = f" (Page {t.get('page')})" if t.get("page") else ""
                            lines.append(f"- **{t.get('point')}**{page_info}")
                            lines.append(f'  > *"{t.get("quote")}"*')
                    lines.append("\n---\n")
                except Exception:
                    continue

        if flashcards:
            lines.append("## 2. Flashcard Deck\n")
            for idx, fc in enumerate(flashcards, 1):
                try:
                    data = json.loads(fc.payload_json)
                    page_info = f" (Page {data.get('page')})" if data.get("page") else ""
                    lines.append(f"**Card {idx}: {data.get('question')}**")
                    lines.append(f"- **Answer:** {data.get('answer')}")
                    lines.append(f'- *Source Proof{page_info}:* "{data.get("quote")}"\n')
                except Exception:
                    continue
            lines.append("---\n")

        if quizzes:
            lines.append("## 3. Practice Quiz & Self-Assessment\n")
            for idx, q in enumerate(quizzes, 1):
                try:
                    data = json.loads(q.payload_json)
                    letters = ["A", "B", "C", "D"]
                    corr_idx = data.get("correct_answer_index", 0)
                    corr_letter = letters[corr_idx] if corr_idx < len(letters) else "A"

                    lines.append(f"### Question {idx}: {data.get('stem')}\n")
                    for o_idx, opt in enumerate(data.get("options", [])):
                        let = letters[o_idx] if o_idx < len(letters) else f"{o_idx + 1}"
                        lines.append(f"- [{let}] {opt}")
                    lines.append(f"\n- **Correct:** Option {corr_letter}")
                    lines.append(f"- **Explanation:** {data.get('explanation')}")
                    lines.append(f'- **Quote:** "{data.get("quote")}"\n')
                except Exception:
                    continue

        return "\n".join(lines)
